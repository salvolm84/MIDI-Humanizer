#pragma once

#include "DrumMap.h"

#include <juce_data_structures/juce_data_structures.h>
#include <vector>

namespace mh
{

/** One note in a clip.

    Times are in quarter notes (PPQ) measured from the clip start, not in samples or
    seconds, so a clip keeps its musical meaning when the host tempo changes.
*/
struct Note
{
    double startPpq  = 0.0;
    double lengthPpq = 0.25;
    int    noteNumber = 36;
    int    velocity   = 100;   ///< 1..127
    int    channel    = 10;    ///< 1..16, GM drums default to 10

    /** Stable identity used to seed this note's deterministic randomness. Source notes
        get their index in the loaded clip; generated notes (ghosts, flams) get ids from
        a separate high range so they never collide.
    */
    int    sourceId   = 0;

    bool   isGhost    = false; ///< generated by the humanizer, not present in the source
    bool   isFlam     = false; ///< grace half of a flam pair; exempt from the min-gap rule

    /** The note number actually sent, which a drum map's output note may differ from.
        `noteNumber` stays the lane the note is drawn on, so remapping never disturbs the
        grid. -1 means "same as noteNumber".
    */
    int    outputNote = -1;

    /** False when the lane is muted, or another lane is soloed. Inaudible notes are still
        drawn, hollow, so nothing appears to vanish from the clip.
    */
    bool   audible    = true;

    int    emittedNote() const noexcept { return outputNote >= 0 ? outputNote : noteNumber; }

    double endPpq() const noexcept       { return startPpq + lengthPpq; }
    bool operator< (const Note& o) const { return startPpq < o.startPpq; }
};

/** A drum clip: a bag of notes plus the musical context needed to draw and play it. */
class NoteSequence
{
public:
    NoteSequence() = default;

    std::vector<Note> notes;

    /** Musical length of the clip, in quarter notes. Playback loops over this. */
    double lengthPpq = 4.0;

    /** Tempo stored in the source MIDI file, used as a fallback when no host is running. */
    double sourceBpm = 120.0;

    int timeSigNumerator   = 4;
    int timeSigDenominator = 4;

    juce::String name;

    bool isEmpty() const noexcept  { return notes.empty(); }
    int  size()    const noexcept  { return (int) notes.size(); }

    void clear();

    /** Sorts by start time, then note number. Playback and several humanization stages
        assume time order.
    */
    void sortByTime();

    /** Distinct note numbers present, ordered for display top-to-bottom (see laneSortKey). */
    std::vector<int> lanesForDisplay() const;

    /** Length of one bar in quarter notes, from the clip's time signature. */
    double barLengthPpq() const noexcept;

    /** Rounds lengthPpq up to a whole number of bars, with at least one bar. */
    void snapLengthToBars();

    /** Highest velocity in the clip, or 0 when empty. */
    int peakVelocity() const noexcept;

    /** Assigns sourceId = index. Call after loading so ids are dense and stable. */
    void assignSourceIds();

    /** Round-trips the clip through plugin state, so a dropped clip survives closing
        and reopening the project. Notes go into one packed binary property rather than
        a child tree each, which keeps large clips cheap to save.
    */
    juce::ValueTree toValueTree() const;
    void restoreFromValueTree (const juce::ValueTree& tree);
};

} // namespace mh
